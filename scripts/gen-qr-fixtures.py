#!/usr/bin/env python3
"""
Regenerate tests/fixtures/qr-ref.json from the reference `qrcode` package.

    python3 -m venv .venv && .venv/bin/pip install qrcode
    .venv/bin/python scripts/gen-qr-fixtures.py

Byte mode is forced (`MODE_8BIT_BYTE`) because Luncher's encoder implements byte
mode only — the right choice for URLs and share links, which contain lowercase
characters the alphanumeric mode cannot represent. Matrices are packed as
base64 of row-bitmaps so the fixture stays small enough to commit.
"""
import base64, json, os
import qrcode, qrcode.util as QU
from qrcode.constants import ERROR_CORRECT_L, ERROR_CORRECT_M, ERROR_CORRECT_Q, ERROR_CORRECT_H

EC = {'L': ERROR_CORRECT_L, 'M': ERROR_CORRECT_M, 'Q': ERROR_CORRECT_Q, 'H': ERROR_CORRECT_H}

SAMPLES = [
    ('HI', 'L'),
    ('https://luncher.example.workers.dev/sub/0f3c1a9b7e5d4c2b1a0988776655443', 'M'),
    ('vless://a3f1c2d4-5b6e-4f70-8a91-b2c3d4e5f607@188.114.97.6:443?type=ws'
     '&host=luncher.example.workers.dev&path=%2Fluncher%3Fed%3D2048&security=tls&fp=unsafe#Luncher', 'Q'),
    ('سلام دنیا — Luncher ۱۲۳', 'M'),
    ('x' * 60, 'H'),
    ('y' * 120, 'M'),
    ('z' * 220, 'L'),
    ('w' * 400, 'L'),
]


def pack(matrix):
    rows = []
    for row in matrix:
        bits = bytearray((len(row) + 7) // 8)
        for c, v in enumerate(row):
            if v:
                bits[c // 8] |= 0x80 >> (c % 8)
        rows.append(bytes(bits))
    return base64.b64encode(b''.join(rows)).decode()


def main():
    out = {'note': 'generated by scripts/gen-qr-fixtures.py — do not edit by hand',
           'byteModeOnly': True, 'cases': []}
    for text, ec in SAMPLES:
        for mask in range(8):
            qr = qrcode.QRCode(error_correction=EC[ec], box_size=1, border=0, mask_pattern=mask)
            qr.add_data(QU.QRData(text.encode('utf-8'), mode=QU.MODE_8BIT_BYTE))
            qr.make(fit=True)
            ref = [[1 if c else 0 for c in r] for r in qr.get_matrix()]
            out['cases'].append({'text': text, 'ec': ec, 'mask': mask,
                                 'version': qr.version, 'size': len(ref), 'modules': pack(ref)})
    path = os.path.join(os.path.dirname(__file__), '..', 'tests', 'fixtures', 'qr-ref.json')
    with open(os.path.normpath(path), 'w') as f:
        json.dump(out, f)
    print(f'wrote {len(out["cases"])} cases to {os.path.normpath(path)} '
          f'({os.path.getsize(os.path.normpath(path))} bytes)')


if __name__ == '__main__':
    main()
